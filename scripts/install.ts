import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';
import { BRANDING, GLOBAL_OWNER_ID } from '../src/config/branding';
import { SqliteDatabase } from '../src/database/connection';
import { MigrationRunner } from '../src/database/migrator';
import { generateAllVisualAssets } from '../src/services/AssetGeneratorService';
import dotenv from 'dotenv';

async function runInstaller(): Promise<void> {
  console.log('==================================================================');
  console.log(`  ${BRANDING.projectName} — SAFE PRODUCTION INSTALLER`);
  console.log(`  ${BRANDING.creatorIdentity} | Discord: ${BRANDING.creatorDiscordUsername}`);
  console.log(`  Permanent Global Owner ID: ${GLOBAL_OWNER_ID}`);
  console.log('==================================================================\n');

  const envPath = path.resolve(process.cwd(), '.env');
  let dbRelativePath = './data/tanveer-monitor.sqlite';

  if (fs.existsSync(envPath)) {
    console.log(`[SAFEGUARD] Existing ".env" detected at ${envPath}.`);
    console.log('[SAFEGUARD] Refusing to overwrite existing ".env" configuration.\n');
    const existing = dotenv.parse(fs.readFileSync(envPath));
    if (existing.DATABASE_PATH) dbRelativePath = existing.DATABASE_PATH;
    if (!existing.DISCORD_CLIENT_SECRET) {
      console.log('[WEBSITE] DISCORD_CLIENT_SECRET is missing, so dashboard sign-in stays disabled.');
      console.log('[WEBSITE] Add DISCORD_CLIENT_SECRET and OAUTH2_REDIRECT_URI to ".env" to enable the dashboard.\n');
    }
  } else {
    if (!input.isTTY) {
      throw new Error(
        'Interactive terminal required to prompt for secrets when ".env" does not exist. Copy ".env.example" to ".env" manually in non-interactive CI/containers.',
      );
    }

    const rl = readline.createInterface({ input, output });
    try {
      const token = (await rl.question('1. Enter Discord Bot Token (DISCORD_TOKEN): ')).trim();
      const clientId = (await rl.question('2. Enter Discord Application ID (DISCORD_CLIENT_ID): ')).trim();
      const devGuildId = (
        await rl.question('3. Optional Developer Guild ID for instant command sync (press Enter for global): ')
      ).trim();
      const ownerConfirm = (
        await rl.question(`4. Confirm Permanent Global Owner ID [${GLOBAL_OWNER_ID}]: `)
      ).trim();

      if (ownerConfirm && ownerConfirm !== GLOBAL_OWNER_ID) {
        console.log(
          `[SECURITY] Permanent Global Owner ID is immutably locked to ${GLOBAL_OWNER_ID}; ignoring custom input.`,
        );
      }

      const customDb = (
        await rl.question('5. Persistent SQLite Database Path [./data/tanveer-monitor.sqlite]: ')
      ).trim();
      if (customDb) {
        if (customDb.startsWith('/tmp')) {
          throw new Error('Unsafe database path: SQLite database must be stored in persistent storage, never /tmp.');
        }
        dbRelativePath = customDb;
      }

      const webBaseUrl = (
        await rl.question('6. Dashboard public URL [http://localhost:3000]: ')
      ).trim() || 'http://localhost:3000';
      const clientSecret = (
        await rl.question('7. Optional Discord OAuth2 Client Secret for the dashboard (press Enter to skip): ')
      ).trim();
      if (!token || !clientId) {
        throw new Error('DISCORD_TOKEN and DISCORD_CLIENT_ID are required to generate ".env".');
      }

      const envContent = [
        `# Generated by ${BRANDING.projectName} Safe Installer`,
        `DISCORD_TOKEN=${token}`,
        `DISCORD_CLIENT_ID=${clientId}`,
        `DISCORD_DEV_GUILD_ID=${devGuildId}`,
        `GLOBAL_OWNER_ID=${GLOBAL_OWNER_ID}`,
        `DATABASE_PATH=${dbRelativePath}`,
        `DATABASE_BACKUP_DIR=./data/backups`,
        `REPORT_EXPORT_DIR=./data/exports`,
        `ENABLE_GUILD_MEMBERS_INTENT=true`,
        `ENABLE_PRESENCE_INTENT=false`,
        `ENABLE_MESSAGE_CONTENT_INTENT=false`,
        `DEFAULT_SCAN_INTERVAL_MINUTES=360`,
        `SCHEDULER_TICK_SECONDS=60`,
        `AUTO_REGISTER_COMMANDS_ON_STARTUP=true`,
        `WEB_ENABLED=true`,
        `WEB_HOST=0.0.0.0`,
        `WEB_PORT=3000`,
        `WEB_BASE_URL=${webBaseUrl.replace(/\/$/, '')}`,
        `OAUTH2_REDIRECT_URI=${webBaseUrl.replace(/\/$/, '')}/auth/callback`,
        `DISCORD_CLIENT_SECRET=${clientSecret}`,
        `COOKIE_SECURE=auto`,
        `WEB_TRUST_PROXY=false`,
        `NODE_ENV=production`,
        `LOG_LEVEL=info`,
        '',
      ].join('\n');

      fs.writeFileSync(envPath, envContent, { mode: 0o600 });
      console.log(`\n[OK] Created ".env" safely with mode 0600.`);
    } finally {
      rl.close();
    }
  }

  // Initialize or migrate persistent SQLite database without overwriting existing records
  const resolvedDb = path.resolve(process.cwd(), dbRelativePath);
  const dbExisted = fs.existsSync(resolvedDb);
  const db = new SqliteDatabase(resolvedDb);
  try {
    const migrator = new MigrationRunner(db);
    const applied = migrator.runMigrations();
    console.log(
      dbExisted
        ? `[SAFEGUARD] Existing persistent database preserved at ${resolvedDb} (${applied.length} new migration(s) applied).`
        : `[OK] Initialized persistent SQLite database at ${resolvedDb} (${applied.length} migration(s) applied).`,
    );
  } finally {
    db.close();
  }

  const assets = generateAllVisualAssets();
  console.log(
    `[OK] Verified ${assets.bannersGenerated.length} banner assets and ${assets.emojisGenerated.length} custom emoji assets.`,
  );
  console.log('\nSetup complete! Run `npm run build && npm start` to launch TANVEER STAFF MONITOR.');
  if (!fs.existsSync(envPath) || !dotenv.parse(fs.readFileSync(envPath)).DISCORD_CLIENT_SECRET) {
    console.log('Dashboard sign-in remains disabled until DISCORD_CLIENT_SECRET is set in ".env".');
    console.log('Discord Developer Portal → OAuth2 → Redirects must include your /auth/callback URL.');
  }
}

void runInstaller().catch((err) => {
  console.error('[INSTALLER ERROR]', err instanceof Error ? err.message : err);
  process.exit(1);
});
